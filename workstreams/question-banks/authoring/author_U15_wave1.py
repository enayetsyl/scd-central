    import unicodedata
    def norm(s):
        s = unicodedata.normalize("NFC", s or "")
        s = re.sub(r"[‘’“”'\"()\[\]।,;:?!—–\-….*_#>|/·]", " ", s)
        return re.sub(r"\s+", " ", s).strip()
