Q, POOLS, SLOTS, SRCS = [], {"HW": [], "AS": [], "CT": []}, {}, {}
_n = 0


def add(pool, slot, source, **payload):
    global _n
    _n += 1
    qid = f"QP-BAN-C5-U21-Q{_n:02d}"
    payload["qid"] = qid
    payload.setdefault("tier", "tier1")
    Q.append(payload)
    POOLS[pool].append(qid)
    SLOTS[qid] = slot
    SRCS[qid] = source
    return qid


def mcq(pool, text, opts, bloom, diff, source, topic=TOP_INFO, ref19="BAN-INFOTEXT"):
    """opts: list of (label, text, is_correct, why_wrong)"""
    return add(pool, "S05", source, topic_tag=topic, ref19_topic_id=ref19,
               question_text=text, question_type="mcq", paper_role="mcq",
               bloom_level=bloom, difficulty=diff, marks=1,
               options=[{"option_id": l, "text": t, "is_correct": c,
                         **({} if c else {"why_wrong": w})} for l, t, c, w in opts])


def tf(pool, text, ans, bloom, diff, source):
    return add(pool, "S05", source, topic_tag=TOP_INFO, ref19_topic_id="BAN-INFOTEXT",
               question_text=text, question_type="true_false", paper_role="mcq",
               bloom_level=bloom, difficulty=diff, marks=1, tf_answer=ans)


def sa(pool, slot, text, accepted, marks, bloom, diff, source, topic=TOP_INFO,
       ref19="BAN-INFOTEXT", note=None):
    ak = {"accepted": accepted}
    if note:
        ak["model_note"] = note
    return add(pool, slot, source, topic_tag=topic, ref19_topic_id=ref19,
               question_text=text, question_type="short_answer", paper_role="short",
               bloom_level=bloom, difficulty=diff, marks=marks, answer_key=ak)


